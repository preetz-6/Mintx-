"""Build the Mintx PII dataset.

    python ml/data/fetch_ai4privacy.py   # once: download the ai4privacy sample (~25k rows)
    python ml/data/build.py              # generate, relabel, split, validate, write stats

Outputs in ml/data/processed/:
  train.jsonl, val.jsonl      synthetic (training templates) + ai4privacy train sample
  test_synthetic.jsonl        synthetic examples from held-out templates
  test_ai4privacy.jsonl       ai4privacy validation sample (in-distribution for ai4privacy)
  test_realistic.jsonl        hand-checked, non-template examples (out-of-distribution)
"""
from __future__ import annotations

import collections
import hashlib
import json
import re
from pathlib import Path

from common import HERE, LABELS, read_jsonl, validate, write_jsonl
from generate import generate
from relabel import relabel

RAW = HERE / "raw"
OUT = HERE / "processed"
MARKUP = re.compile(r"\[\[(.+?)\|([A-Z_]+)\]\]|\{\{(.+?)\|([a-z_]+)\}\}")


def parse_realistic(path: Path) -> list[dict]:
    blocks = [b.strip("\n") for b in re.split(r"^~~~$", path.read_text(encoding="utf-8"), flags=re.M)]
    records = []
    for i, block in enumerate(blocks):
        block = "\n".join(line for line in block.splitlines() if not line.startswith("#")).strip("\n")
        if not block.strip():
            continue
        text, spans, keep, pos = "", [], [], 0
        for m in MARKUP.finditer(block):
            text += block[pos:m.start()]
            value, label = (m.group(1), m.group(2)) if m.group(1) else (m.group(3), m.group(4))
            start = len(text)
            text += value
            (spans if m.group(1) else keep).append(
                {"start": start, "end": start + len(value), **({"label": label} if m.group(1) else {"kind": label})})
            pos = m.end()
        text += block[pos:]
        rec = {"id": f"real-{i:03d}", "text": text, "spans": spans, "keep": keep, "source": "realistic",
               "domain": "realistic", "template": None, "split": "test_realistic"}
        problems = validate(rec)
        if problems:
            raise ValueError(f"realistic example {i}: {problems}")
        records.append(rec)
    return records


def bucket(uid) -> int:
    return int(hashlib.sha1(str(uid).encode()).hexdigest(), 16) % 10


def load_ai4privacy() -> tuple[list[dict], list[dict], list[dict]]:
    train, val, test = [], [], []
    for split, target in (("train", None), ("validation", test)):
        path = RAW / f"ai4privacy_{split}.jsonl"
        if not path.exists():
            print(f"  (skipping ai4privacy {split}: run fetch_ai4privacy.py first)")
            continue
        seen = set()
        for row in read_jsonl(path):
            if row["uid"] in seen:
                continue
            seen.add(row["uid"])
            rec = relabel(row)
            if not rec:
                continue
            if target is test:
                rec["split"] = "test_ai4privacy"; test.append(rec)
            elif bucket(row["uid"]) == 0:
                rec["split"] = "val"; val.append(rec)
            else:
                rec["split"] = "train"; train.append(rec)
    return train, val, test


def stats(files: dict[str, list[dict]]) -> str:
    lines = ["# Dataset statistics", "", "Generated by `ml/data/build.py`. Labels follow `labeling_policy.md`.", "",
             "| File | Examples | Synthetic | ai4privacy | Realistic | PII spans | Keep spans | Avg. characters |",
             "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for name, recs in files.items():
        src = collections.Counter(r["source"] for r in recs)
        lines.append(f"| `{name}` | {len(recs):,} | {src['synthetic']:,} | {src['ai4privacy']:,} | {src['realistic']:,} | "
                     f"{sum(len(r['spans']) for r in recs):,} | {sum(len(r['keep']) for r in recs):,} | "
                     f"{sum(len(r['text']) for r in recs) // max(1, len(recs))} |")
    lines += ["", "## PII spans per label", "", "| Label | " + " | ".join(f"`{n}`" for n in files) + " |",
              "| --- |" + " ---: |" * len(files)]
    counts = {n: collections.Counter(s["label"] for r in recs for s in r["spans"]) for n, recs in files.items()}
    for label in LABELS:
        lines.append(f"| {label} | " + " | ".join(f"{counts[n][label]:,}" for n in files) + " |")
    keeps = {n: collections.Counter(k["kind"] for r in recs for k in r["keep"]) for n, recs in files.items()}
    lines += ["", "## Keep (public) spans per kind", "", "| Kind | " + " | ".join(f"`{n}`" for n in files) + " |",
              "| --- |" + " ---: |" * len(files)]
    for kind in sorted({k for c in keeps.values() for k in c}):
        lines.append(f"| {kind} | " + " | ".join(f"{keeps[n][kind]:,}" for n in files) + " |")
    lines += ["", "## Synthetic domains", "", "| Domain | Train | Val | Test |", "| --- | ---: | ---: | ---: |"]
    dom = collections.Counter((r["domain"], r["split"]) for recs in files.values() for r in recs if r["source"] == "synthetic")
    for d in sorted({d for d, _ in dom}):
        lines.append(f"| {d} | {dom[(d, 'train')]} | {dom[(d, 'val')]} | {dom[(d, 'test')]} |")
    lines += ["", "## Sample records", ""]
    for name, recs in files.items():
        r = recs[len(recs) // 3]
        lines += [f"**{name}** (`{r['id']}`)", "", "```", r["text"][:400], "```",
                  "Mask: " + ", ".join(f"`{r['text'][s['start']:s['end']]}` → {s['label']}" for s in r["spans"]) or "none",
                  "", "Keep: " + (", ".join(f"`{r['text'][k['start']:k['end']]}`" for k in r["keep"]) or "none"), ""]
    lines += ["## Attribution", "",
              "Rows with `source: ai4privacy` are derived from *OpenPII 1.5M* by Ai4Privacy / Ai Suisse SA "
              "(https://huggingface.co/datasets/ai4privacy/pii-masking-openpii-1.5m), licensed CC-BY-4.0, "
              "relabelled to the Mintx policy as described in `labeling_policy.md`."]
    return "\n".join(lines) + "\n"


def main():
    print("generating synthetic examples…")
    syn = generate()
    print("relabelling ai4privacy…")
    a_train, a_val, a_test = load_ai4privacy()
    print("parsing realistic test set…")
    real = parse_realistic(HERE / "realistic_test.txt")

    files = {
        "train.jsonl": [r for r in syn if r["split"] == "train"] + a_train,
        "val.jsonl": [r for r in syn if r["split"] == "val"] + a_val,
        "test_synthetic.jsonl": [r for r in syn if r["split"] == "test"],
        "test_ai4privacy.jsonl": a_test,
        "test_realistic.jsonl": real,
    }
    # No text may appear in both training data and any evaluation file.
    held_out = {r["text"] for name, recs in files.items() if name != "train.jsonl" for r in recs}
    before = len(files["train.jsonl"])
    files["train.jsonl"] = [r for r in files["train.jsonl"] if r["text"] not in held_out]
    print(f"removed {before - len(files['train.jsonl'])} training texts duplicated in eval sets")

    for name, recs in files.items():
        bad = [(r["id"], validate(r)) for r in recs if validate(r)]
        if bad:
            raise ValueError(f"{name}: {bad[:3]}")
        write_jsonl(OUT / name, recs)
        print(f"  {name:24} {len(recs):>6,} examples")
    (HERE / "stats.md").write_text(stats(files), encoding="utf-8")
    (OUT / "label_map.json").write_text(json.dumps({"labels": LABELS}, indent=2), encoding="utf-8")
    print("wrote", OUT, "and stats.md")


if __name__ == "__main__":
    main()
