"""Train the "mask or keep?" decision classifier on candidates exported by export_features.py.

    python ml/classifier/train.py

Compares the current hand-set rule (fused confidence >= 0.5) with logistic regression and gradient
boosting using 5-fold grouped cross-validation (candidates from one text stay in one fold), evaluates
on three held-out test sets, and exports the chosen model to assistant/pii/classifier-model.js.
Writes metrics and plots to ml/results/classifier/.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from sklearn.calibration import calibration_curve
from sklearn.ensemble import GradientBoostingClassifier
from sklearn.inspection import permutation_importance
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (average_precision_score, brier_score_loss, f1_score, precision_recall_curve,
                             precision_score, recall_score, roc_auc_score)
from sklearn.model_selection import GroupKFold
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "ml/results/classifier"
FEATURES = HERE / "features"
EXPORT = ROOT / "assistant/pii/classifier-model.js"
TESTS = ["test_synthetic", "test_realistic", "test_ai4privacy"]
SEED = 42


def feature_names() -> list[str]:
    return json.loads((FEATURES / "feature_names.json").read_text(encoding="utf-8"))


def load(split):
    rows = [json.loads(l) for l in open(FEATURES / f"{split}.jsonl", encoding="utf-8")]
    return rows, np.array([r["x"] for r in rows], float), np.array([r["y"] for r in rows]), np.array([r["id"] for r in rows])


def scores(y, p, rows=None, cut=0.5):
    pred = p >= cut
    out = {"roc_auc": roc_auc_score(y, p) if len(set(y)) > 1 else float("nan"),
           "pr_auc": average_precision_score(y, p), "precision": precision_score(y, pred, zero_division=0),
           "recall": recall_score(y, pred), "f1": f1_score(y, pred), "brier": brier_score_loss(y, np.clip(p, 0, 1))}
    if rows is not None:
        keep = np.array([r["keep"] for r in rows], bool)
        out["public_kept"] = float((~pred[keep]).mean()) if keep.any() else float("nan")
        out["n"] = len(y)
    return out


STRUCTURED = {"EMAIL", "PHONE", "GOV_ID", "AADHAAR", "PAN", "SSN", "PASSPORT", "CREDIT_CARD", "BANK_ACCOUNT", "IBAN",
              "UPI_ID", "IP_ADDRESS", "SECRET"}
FLOOR = 0.7   # formatted identifiers the rules are this sure about cannot be vetoed by the classifier


def with_floor(rows, p):
    """Same safety floor as assistant/pii/engine.js."""
    return np.array([max(pi, r["fused"]) if r["type"] in STRUCTURED and r["fused"] >= FLOOR else pi for r, pi in zip(rows, p)])


MODELS = {
    "logistic regression": lambda: make_pipeline(StandardScaler(), LogisticRegression(C=1.0, max_iter=2000)),
    "gradient boosting": lambda: GradientBoostingClassifier(n_estimators=150, max_depth=3, learning_rate=0.1,
                                                            subsample=0.8, random_state=SEED),
}


def export(name, model, names, policies):
    if name == "logistic regression":
        scaler, lr = model.named_steps["standardscaler"], model.named_steps["logisticregression"]
        payload = {"kind": "lr", "intercept": float(lr.intercept_[0]), "coef": lr.coef_[0].round(6).tolist(),
                   "mean": scaler.mean_.round(6).tolist(), "scale": np.where(scaler.scale_ == 0, 1, scaler.scale_).round(6).tolist()}
    else:
        trees = []
        for est in model.estimators_[:, 0]:
            t = est.tree_
            trees.append({"left": t.children_left.tolist(), "right": t.children_right.tolist(), "feature": t.feature.tolist(),
                          "threshold": t.threshold.round(6).tolist(), "value": t.value[:, 0, 0].round(6).tolist()})
        init = float(model._raw_predict_init(np.zeros((1, len(names))))[0, 0])
        payload = {"kind": "gb", "init": init, "learning_rate": model.learning_rate, "trees": trees}
    payload["features"] = names
    payload["policies"] = policies
    payload["floor"] = FLOOR
    EXPORT.write_text("// Generated by ml/classifier/train.py — the learned mask/keep decision model.\n"
                      f"export const CLASSIFIER = {json.dumps(payload, separators=(',', ':'))};\n", encoding="utf-8")
    pub = json.loads((ROOT / "ml/data/public_entities.json").read_text(encoding="utf-8"))
    names_pub = sorted({v.lower() for vals in pub.values() if isinstance(vals, list) for v in vals})
    (ROOT / "assistant/pii/public-entities.js").write_text(
        "// Generated from ml/data/public_entities.json by ml/classifier/train.py — edit the JSON, not this file.\n"
        "// Public names (countries, regions, large organizations, public figures) used as a classifier feature.\n"
        f"export const PUBLIC_NAMES = new Set({json.dumps(names_pub, ensure_ascii=False)});\n", encoding="utf-8")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    names = feature_names()
    rows, X, y, groups = load("val")
    assert X.shape[1] == len(names), f"{X.shape[1]} features but {len(names)} names"
    print(f"training set (validation split): {len(y):,} candidates, {y.mean():.1%} personal data")

    # 1. Grouped cross-validation on the validation split
    cv = GroupKFold(n_splits=5)
    oof = {"fixed rule (fused ≥ 0.5)": X[:, names.index("fused_score")]}
    for name, make in MODELS.items():
        p = np.zeros(len(y))
        for tr, te in cv.split(X, y, groups):
            p[te] = make().fit(X[tr], y[tr]).predict_proba(X[te])[:, 1]
        oof[name] = p
    cv_table = {name: scores(y, p, rows) for name, p in oof.items()}

    # 2. Fit on all validation candidates, evaluate on held-out test sets
    fitted = {name: make().fit(X, y) for name, make in MODELS.items()}
    test_table, test_pred = {}, {}
    for split in TESTS:
        trows, tX, ty, _ = load(split)
        test_pred[split] = {"fixed rule (fused ≥ 0.5)": tX[:, names.index("fused_score")],
                            **{n: m.predict_proba(tX)[:, 1] for n, m in fitted.items()}}
        for name, p in test_pred[split].items():
            test_table[(name, split)] = scores(ty, p, trows)

    # 3. Choose: logistic regression unless boosting is clearly better (interpretability, size)
    combined = {n: np.mean([test_table[(n, s)]["pr_auc"] for s in TESTS]) for n in MODELS}
    choice = "gradient boosting" if combined["gradient boosting"] > combined["logistic regression"] + 0.01 else "logistic regression"
    # Operating point, chosen on out-of-fold predictions only (never on test data): the highest
    # cut-off whose recall matches the fixed rule's, so the classifier never trades privacy away.
    rule_recall = (X[:, names.index("fused_score")] >= 0.5)[y == 1].mean()
    oof_floor = with_floor(rows, oof[choice])
    balanced = next(c for c in np.round(np.arange(0.5, 0.0, -0.01), 2) if (oof_floor >= c)[y == 1].mean() >= rule_recall)
    policies = {"strict": round(balanced / 2, 3), "balanced": float(balanced), "relaxed": 0.5}
    export(choice, fitted[choice], names, policies)
    op_table = {}
    for split in TESTS:
        trows, tX, ty, _ = load(split)
        op_table[("fixed rule (fused ≥ 0.5)", split)] = scores(ty, tX[:, names.index("fused_score")], trows, 0.5)
        op_table[(f"{choice} @ {balanced} + safety floor", split)] = scores(ty, with_floor(trows, test_pred[split][choice]), trows, balanced)

    # 4. Plots
    fig, ax = plt.subplots(1, 3, figsize=(15, 4.2))
    for name, p in oof.items():
        pr, rc, _ = precision_recall_curve(y, p)
        ax[0].plot(rc, pr, label=f"{name} (AP {average_precision_score(y, p):.3f})")
        if name != "fixed rule (fused ≥ 0.5)":
            fp, mp = calibration_curve(y, p, n_bins=10)
            ax[1].plot(mp, fp, "o-", label=name)
    fp, mp = calibration_curve(y, np.clip(oof["fixed rule (fused ≥ 0.5)"], 0, 1), n_bins=10)
    ax[1].plot(mp, fp, "s--", label="fused confidence")
    ax[1].plot([0, 1], [0, 1], "k:", lw=1)
    ax[0].set(xlabel="recall", ylabel="precision", title="Precision–recall (cross-validated)"); ax[0].legend(fontsize=8)
    ax[1].set(xlabel="predicted probability", ylabel="observed share of PII", title="Calibration (cross-validated)"); ax[1].legend(fontsize=8)
    lr = fitted["logistic regression"].named_steps["logisticregression"]
    order = np.argsort(np.abs(lr.coef_[0]))[-15:]
    ax[2].barh([names[i] for i in order], lr.coef_[0][order], color=["#1f8a70" if c > 0 else "#b5427a" for c in lr.coef_[0][order]])
    ax[2].set(title="Logistic regression: top weights (standardized)", xlabel="← keep visible      mask →")
    plt.tight_layout(); plt.savefig(OUT / "classifier.png", dpi=150); plt.close()

    gb = fitted["gradient boosting"]
    _, tX, ty, _ = load("test_realistic")
    perm = permutation_importance(gb, X, y, n_repeats=5, random_state=SEED, scoring="average_precision")
    top = np.argsort(perm.importances_mean)[-12:]
    plt.figure(figsize=(6, 4.2))
    plt.barh([names[i] for i in top], perm.importances_mean[top], xerr=perm.importances_std[top], color="#2f6fdb")
    plt.title("Gradient boosting: permutation importance (PR AUC drop)"); plt.tight_layout()
    plt.savefig(OUT / "gb_importance.png", dpi=150); plt.close()

    # 5. Report
    fmt = lambda d: " | ".join(f"{d[k]:.3f}" if isinstance(d[k], float) and not np.isnan(d[k]) else "–"
                               for k in ["roc_auc", "pr_auc", "precision", "recall", "f1", "public_kept", "brier"])
    head = "| Model | ROC AUC | PR AUC | Precision | Recall | F1 | Public names kept | Brier |\n| --- |" + " ---: |" * 7
    lines = ["# Decision classifier results", "",
             f"Training data: {len(y):,} candidates from the validation split ({y.mean():.1%} personal data), "
             f"{len(names)} features. Shipped model: **{choice}**.", "",
             "## 5-fold grouped cross-validation (validation split)", "", head]
    lines += [f"| {n} | {fmt(m)} |" for n, m in cv_table.items()]
    for split in TESTS:
        lines += ["", f"## {split} ({test_table[('logistic regression', split)]['n']:,} candidates)", "", head]
        lines += [f"| {n} | {fmt(test_table[(n, split)])} |" for n in test_pred[split]]
    lines += ["", f"## Shipped operating point: {choice} at p ≥ {balanced} (Balanced) with the identifier safety floor", "",
              f"The cut-off is the highest whose cross-validated recall matches the fixed rule ({rule_recall:.4f}). It was chosen on the "
              f"validation split, never on test data. Policies: strict {policies['strict']}, balanced {policies['balanced']}, relaxed "
              f"{policies['relaxed']}. Formatted identifiers that the rules score ≥ {FLOOR} cannot be vetoed.", "", head]
    for split in TESTS:
        for n in [k for k in op_table if k[1] == split]:
            lines.append(f"| {n[0]} · {split} | {fmt(op_table[n])} |")
    lines += ["", "Precision, recall and F1 are at probability 0.5, the Balanced policy. *Public names kept* = share of candidates on "
              "public entities (Google, India…) that the model leaves visible.", "",
              "![classifier](classifier.png)", "", "![importance](gb_importance.png)"]
    (OUT / "metrics.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (OUT / "results.json").write_text(json.dumps({"choice": choice, "policies": policies, "features": names, "cv": cv_table,
        "operating_point": {f"{n} | {s_}": v for (n, s_), v in op_table.items()},
        "test": {f"{n} | {s}": v for (n, s), v in test_table.items()}}, indent=2, default=float), encoding="utf-8")
    print("\n".join(lines[:4 + len(cv_table) + 4]))
    for split in TESTS:
        print(f"\n{split}:")
        for n in test_pred[split]:
            m = test_table[(n, split)]
            print(f"  {n:28} PR-AUC {m['pr_auc']:.3f}  P {m['precision']:.3f}  R {m['recall']:.3f}  F1 {m['f1']:.3f}  public kept {m['public_kept']:.3f}")
    print(f"\noperating point (chosen on validation): balanced cut-off {balanced}")
    for (n, split), m in op_table.items():
        print(f"  {split:16} {n:45} P {m['precision']:.3f}  R {m['recall']:.3f}  F1 {m['f1']:.3f}  public kept {m['public_kept']:.3f}")
    print(f"\nexported {choice} → {EXPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
